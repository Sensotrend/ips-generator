"""Approval: the reviewer attests the Composition (PLAN D-4).

``Composition.author`` stays the pipeline ``Device``. The reviewer becomes a
``Composition.attester``:

* ``personal`` with ``party`` = the Patient, when the reviewer states they are the patient;
* ``professional`` with ``party.display`` = the reviewer's name, for a clinician. (No
  Practitioner resource is added yet: the dev identity has no professional identifiers; with
  OIDC this can become a Practitioner entry or an identifier reference.)

``Composition.status`` becomes ``final``. Applied to an assembled Bundle, so the deterministic
mappers stay unchanged; pure function, no I/O.
"""

from __future__ import annotations

import datetime as dt
from typing import Literal

from app.fhir.composition import AI_STATEMENT, TITLE
from app.fhir.models import Bundle, BundleEntry, Composition, CompositionAttester, Reference
from app.fhir.narrative import NarrativeLine, line_narrative
from app.schemas.api import ReviewerRole

__all__ = ["AttesterMode", "attest_bundle", "attester_mode"]

AttesterMode = Literal["personal", "professional"]


def attester_mode(role: ReviewerRole) -> AttesterMode:
    return "personal" if role is ReviewerRole.PATIENT else "professional"


def attest_bundle(
    bundle: Bundle, *, role: ReviewerRole, reviewer_name: str, at: dt.datetime
) -> Bundle:
    """``bundle`` with its Composition (first entry) final and attested by the reviewer."""
    if at.tzinfo is None:
        raise ValueError("at must be timezone-aware")
    entries = list(bundle.entry or [])
    if not entries or not isinstance(entries[0].resource, Composition):
        raise ValueError("the first Bundle entry must be the Composition")
    composition = entries[0].resource
    mode = attester_mode(role)
    when = at.isoformat(timespec="seconds")
    if mode == "personal":
        if composition.subject is None or composition.subject.reference is None:
            raise ValueError("the Composition has no subject to attest as")
        party = Reference(reference=composition.subject.reference)
        attested_by = "the patient"
    else:
        party = Reference(display=reviewer_name)
        attested_by = f"{reviewer_name} (clinician)"

    details = [("status", "final (human-reviewed)"), ("attested by", attested_by), ("at", when)]
    author = next((a.display for a in composition.author if a.display), None)
    if author:
        details.append(("generated by", author))
    details.append(("AI", AI_STATEMENT))
    details.append(("date", composition.date))
    attested = composition.model_copy(
        update={
            "status": "final",
            "attester": [CompositionAttester(mode=mode, time=when, party=party)],
            "text": line_narrative(NarrativeLine(TITLE, tuple(details))),
        }
    )
    entries[0] = BundleEntry(full_url=entries[0].full_url, resource=attested)
    return bundle.model_copy(update={"entry": entries})
