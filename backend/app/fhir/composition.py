"""Composition-uv-ips: the first entry of the IPS document Bundle.

``type``, section codes and profile come from ``constants`` only (D-1). ``status`` is
``preliminary`` until a reviewer approves the draft (Phase 3 sets ``final`` and adds the
attester). ``author`` is the pipeline Device (D-4); there is no attester yet.
"""

from __future__ import annotations

from collections.abc import Sequence
from uuid import UUID

from app.fhir.common import MappedResource, fixed_concept, reference, urn_uuid
from app.fhir.constants import COMPOSITION_TYPE, PROFILE_COMPOSITION
from app.fhir.models import Composition, CompositionSection, Meta
from app.fhir.narrative import NarrativeLine, line_narrative

TITLE = "Patient Summary"


def build_composition(
    *,
    resource_id: UUID,
    patient_url: str,
    author_url: str,
    author_name: str,
    date: str,
    sections: Sequence[CompositionSection],
) -> MappedResource:
    line = NarrativeLine(
        TITLE,
        (
            ("status", "preliminary (not yet reviewed)"),
            ("generated by", author_name),
            ("date", date),
        ),
    )
    resource = Composition(
        id=str(resource_id),
        meta=Meta(profile=[PROFILE_COMPOSITION]),
        text=line_narrative(line),
        status="preliminary",
        type=fixed_concept(COMPOSITION_TYPE),
        subject=reference(patient_url),
        date=date,
        author=[reference(author_url)],
        title=TITLE,
        section=list(sections),
    )
    return MappedResource("", None, urn_uuid(resource_id), resource)
